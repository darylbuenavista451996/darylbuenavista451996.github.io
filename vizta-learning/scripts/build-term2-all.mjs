// Combines the Grade 9 and Grade 10 Term 2 SQL into ONE file to paste once.
// Run AFTER the two builders:  node scripts/build-term2-g9.mjs && node scripts/build-term2-g10.mjs && node scripts/build-term2-all.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const body = (f) =>
  readFileSync(join(root, 'supabase', f), 'utf8')
    .split('\n')
    .filter((l) => !/^(begin;|commit;|select \(select count)/.test(l) && !l.startsWith('--'))
    .join('\n')
    .trim();
const out = [
  '-- Media Arts Term 2, BOTH grades, in one paste.',
  '--   Grade 9 : Animation (5 lessons, 50 quiz questions)',
  '--   Grade 10: Planning and Editing Your Short Film (7 lessons, 70 quiz questions)',
  '-- Generated by scripts/build-term2-all.mjs. Paste into the Supabase SQL editor and run.',
  '-- Safe to run again: modules are only created if missing, so this will NOT undo a lock',
  '-- or unlock you set on the Modules page. Lesson text and quizzes are refreshed.',
  '-- Both Term 2 modules are created LOCKED. Unlock Term 2 on the teacher Modules page.',
  '',
  'begin;',
  '',
  '-- Grade 9',
  body('term2_g9_animation.sql'),
  '',
  '-- Grade 10',
  body('term2_g10_film.sql'),
  '',
  "select (select count(*) from public.modules where module_id in ('G9-M2','G10-M2')) as modules_expect_2, (select count(*) from public.activities where module_id in ('G9-M2','G10-M2')) as lessons_expect_12, (select count(*) from public.quizzes where module_id in ('G9-M2','G10-M2')) as quiz_questions_expect_120;",
  '',
  'commit;',
  '',
].join('\n');
writeFileSync(join(root, 'supabase', 'term2_all.sql'), out);
console.log('wrote supabase/term2_all.sql');
